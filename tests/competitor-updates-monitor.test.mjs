import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');

test('our changelog contains only shipped first-party release evidence and excludes auto-mirrored competitor updates',()=>{
 const page=read('public/updates/index.html');
 const home=read('public/index.html');
 const nav=read('scripts/navigation.mjs');
 assert.match(page,/<h1>Recent Updates<\/h1>/);
 assert.match(page,/our actual shipped changes/);
 for(const n of [66,67,68,72,73])assert.match(page,new RegExp('pull\\/'+n));
 assert.match(page,/it never automatically changes our calculator code, game data or first-party release notes/);
 assert.match(page,/v1\.17 reference/);
 assert.match(home,/id="home-recent-updates"/);
 assert.match(home,/href="updates\/"/);
 assert.match(nav,/\['updates\/','Recent Updates'\]/);
 assert.doesNotMatch(page,/Tarnished\.dev fixed.*therefore.*we released/i);
});
test('monitor is free, read-only, twice a day and creates review issues, not silent implementation',()=>{
 const code=read('scripts/monitor_tarnished_updates.py');
 const workflow=read('.github/workflows/monitor-tarnished.yml');
 const seed=JSON.parse(read('monitoring/tarnished-dev-baseline.json'));
 assert.match(code,/class RecentUpdatesParser/);
 assert.match(code,/updates-heading/);
 assert.match(code,/edited-same-date/);
 assert.match(code,/FAIL-CLOSED/);
 assert.match(code,/No.*certification|No mirroring competitor code/);
 assert.match(workflow,/17 0,12 \* \* \*/);
 assert.match(workflow,/workflow_dispatch/);
 assert.match(workflow,/pull_request/);
 assert.match(workflow,/gh issue create/);
 assert.match(workflow,/steps\.compare\.outputs\.changed == 'true'/);
 assert.match(workflow,/github\.event_name != 'pull_request'/);
 assert.doesNotMatch(workflow,/merge_pull_request|git push origin main|curl.*post/);
 assert.equal(seed.source,'https://www.tarnished.dev/');
 assert.match(seed.version,/^v[0-9]+(?:\.[0-9]+){1,3}$/);
 assert.ok(seed.entries.length>=2&&seed.entries.length<=6);
 assert.ok(seed.entries.every(e=>/^\d{4}-\d{2}-\d{2}$/.test(e.date)&&/^[a-f0-9]{64}$/.test(e.digest)));
 const external=JSON.parse(read('public/data/tarnished-dev-watch.json'));
 assert.equal(external.source,seed.source);
 assert.equal(external.referenceVersion,seed.version);
 assert.equal(external.fingerprint,seed.fingerprint);
 assert.equal(external.gameDataCertified,false);
 assert.equal(external.ourFeaturesUpdated,false);
 assert.match(seed.fingerprint,/^[a-f0-9]{64}$/);
});

test('external watch widget never makes competitor announcements into our release history',()=>{
 const page=read('public/updates/index.html');
 const widget=read('public/src/tarnished-watch-widget.mjs');
 const monitor=read('scripts/stage_tarnished_safe_sync.py');
 const workflow=read('.github/workflows/monitor-tarnished.yml');
 assert.match(page,/id="external-watch-status"/);
 assert.match(page,/id="external-watch-list"/);
 assert.match(page,/id="external-watch-disclaimer"/);
 assert.match(page,/tarnished-watch-widget\.mjs/);
 assert.match(widget,/document\.createElement\('li'\)/);
 assert.match(widget,/detail\.textContent=entry\.excerpt\.slice\(0,110\)/);
 assert.match(widget,/data\.ourFeaturesUpdated!==false/);
 assert.match(widget,/data\.gameDataCertified!==false/);
 assert.doesNotMatch(widget,/innerHTML|insertAdjacentHTML|eval\(/);
 assert.match(monitor,/monitoring\/tarnished-dev-baseline\.json/);
 assert.match(monitor,/public\/data\/tarnished-dev-watch\.json/);
 assert.match(monitor,/ourFeaturesUpdated': False/);
 assert.match(monitor,/gameDataCertified': False/);
 assert.match(workflow,/python3 scripts\/stage_tarnished_safe_sync\.py/);
 assert.match(workflow,/npm run check/);
 assert.match(workflow,/git diff --name-only/);
 assert.match(workflow,/gh pr create/);
 assert.match(workflow,/gh pr merge/);
 assert.doesNotMatch(workflow,/git add -A|git push origin main|gh release create/);
});
